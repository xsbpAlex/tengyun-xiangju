// 按层取一句：里程碑层走定句，其余按区间档随机
export function pickLadderLine(floor, rng = Math.random) {
  if (LADDER_MILESTONE_LINES[floor]) return LADDER_MILESTONE_LINES[floor];
  const pool = floor <= 100 ? LADDER_LINES.shanjiao : floor <= 500 ? LADDER_LINES.banshan : LADDER_LINES.lintian;
  return pool[Math.floor(rng() * pool.length) % pool.length];
}
