// 抽签：目标房的池子里随机，避开上一条读过的（池子只剩一条时除外）。r 由外部注入便于测试。
export function pickVisitEvent(deptId, lastVisitId, r = Math.random()) {
  const pool = VISIT_EVENTS.filter((e) => e.dept === deptId);
  if (pool.length === 0) return null;
  const avoid = pool.filter((e) => e.id !== lastVisitId);
  const pickFrom = avoid.length > 0 ? avoid : pool;
  return pickFrom[Math.floor(r * pickFrom.length)] ?? pickFrom[pickFrom.length - 1];
}
